// ==================== MAZE ====================
// Classic-style maze (28 cols x 31 rows). # = wall, . = dot, o = power, ' ' = empty, G = ghost house door
const MAZE_TEMPLATE = [
  "############################",
  "#............##............#",
  "#.####.#####.##.#####.####.#",
  "#o####.#####.##.#####.####o#",
  "#..........................#",
  "#.####.##.########.##.####.#",
  "#......##....##....##......#",
  "######.##### ## #####.######",
  "     #.##          ##.#     ",
  "     #.## ###GG### ##.#     ",
  "######.## #      # ##.######",
  "      .   #      #   .      ",
  "######.## #      # ##.######",
  "     #.## ######## ##.#     ",
  "     #.##          ##.#     ",
  "######.## ######## ##.######",
  "#............##............#",
  "#.####.#####.##.#####.####.#",
  "#o..##................##..o#",
  "###.##.##.########.##.##.###",
  "#......##....##....##......#",
  "#.####.#####.##.#####.####.#",
  "#..........................#",
  "############################",
  "                            ",
  "                            ",
  "                            ",
  "                            ",
  "                            ",
  "                            ",
  "                            "
];

const COLS = 28;
const ROWS = 31;
let maze = []; // 2D array: 0=wall, 1=path, 2=dot, 3=power, 4=ghost door

function loadMaze() {
  maze = [];
  for (let r = 0; r < ROWS; r++) {
    maze[r] = [];
    const line = MAZE_TEMPLATE[r] || " ".repeat(COLS);
    for (let c = 0; c < COLS; c++) {
      const ch = line[c] || ' ';
      if (ch === '#') maze[r][c] = 0;
      else if (ch === '.') maze[r][c] = 2;
      else if (ch === 'o') maze[r][c] = 3;
      else if (ch === 'G') maze[r][c] = 4; // door (ghosts can pass, player cannot)
      else maze[r][c] = 1;
    }
  }
}
